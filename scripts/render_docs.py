"""Keep documented output honest.

Every block in README.md and docs/*.md that looks like

    <!-- run: python examples/demo.py -->
    ```text
    ...output...
    ```
    <!-- /run -->

is re-generated by running the command from the repository root.
`python scripts/render_docs.py` rewrites the blocks; `--check` fails if any
block no longer matches a fresh run (CI uses --check).
"""
from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCK = re.compile(r"(<!-- run: (?P<cmd>.+?) -->\n```text\n)(?P<out>.*?)(```\n<!-- /run -->)", re.S)


def run(cmd: str) -> str:
    env = dict(os.environ, PYTHONPATH=str(ROOT), PYTHONHASHSEED="0")
    res = subprocess.run(cmd, shell=True, cwd=ROOT, env=env, capture_output=True, text=True, timeout=600)
    if res.returncode != 0:
        sys.exit(f"command failed ({res.returncode}): {cmd}\n{res.stdout}\n{res.stderr}")
    lines = [ln.rstrip() for ln in res.stdout.strip("\n").splitlines()]
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    files = [ROOT / "README.md", *sorted((ROOT / "docs").rglob("*.md"))]
    cache: dict[str, str] = {}
    drift = []
    for path in files:
        if not path.exists():
            continue
        text = path.read_text()

        def repl(m: re.Match, path: pathlib.Path = path) -> str:
            cmd = m.group("cmd")
            if cmd not in cache:
                cache[cmd] = run(cmd)
            if cache[cmd] != m.group("out"):
                drift.append(f"{path.relative_to(ROOT)}: {cmd}")
            return m.group(1) + cache[cmd] + m.group(4)

        new = BLOCK.sub(repl, text)
        if not check and new != text:
            path.write_text(new)
    if check and drift:
        print("Documented output no longer matches a fresh run:")
        print("\n".join(f"  - {d}" for d in drift))
        print("Run: python scripts/render_docs.py")
        return 1
    print(f"{len(cache)} documented command(s) {'match' if check else 'rendered'}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
